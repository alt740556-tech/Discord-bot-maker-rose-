const express = require('express');
const path = require('path');
const fs = require('fs');
const dotenv = require('dotenv');
const { Client, GatewayIntentBits, EmbedBuilder } = require('discord.js');

dotenv.config();

const app = express();
const PORT = process.env.PORT || 3000;
const BOT_NAME = process.env.BOT_NAME || 'Rose AI';
const BOT_DESCRIPTION = process.env.BOT_DESCRIPTION || 'help: Shows available commands\nping: Checks the bot status\nstatus: Shows bot uptime';
const DISCORD_TOKEN = process.env.DISCORD_TOKEN || '';
const DISCORD_CLIENT_ID = process.env.DISCORD_CLIENT_ID || '';

app.use(express.json());
app.use(express.static(path.join(__dirname, 'public')));

function normalizeValue(value) {
  return String(value || '').trim();
}

function parseBotDescription(description) {
  const text = normalizeValue(description);
  if (!text) {
    return [
      { name: 'help', description: 'Shows the available commands.', response: 'Here are my commands: `help`, `ping`, `status`.' },
      { name: 'ping', description: 'Checks the bot latency.', response: 'Pong! Rose AI is online and ready.' },
      { name: 'status', description: 'Shows the current bot status.', response: 'Status: All systems are online.' }
    ];
  }

  const commands = [];
  const lines = text
    .split(/\r?\n|;|\|/)
    .map((line) => line.trim())
    .filter(Boolean);

  lines.forEach((line) => {
    const clean = line.replace(/^[-*•\d.\s]+/, '');
    const match = clean.match(/(?:^|\s)(?:\/)?([a-zA-Z0-9_-]+)\s*(?::|-|=>)?\s*(.*)/i);

    if (match) {
      const name = match[1].toLowerCase();
      const description = normalizeValue(match[2]) || `Runs the ${name} command.`;
      if (!commands.some((cmd) => cmd.name === name)) {
        commands.push({
          name,
          description,
          response: description
        });
      }
    }
  });

  if (commands.length === 0) {
    const genericWords = text.split(/\s+/).filter((word) => word.length > 3);
    const fallback = ['help', 'ping', 'status', 'info'];
    const keywords = [...new Set([...fallback, ...genericWords.slice(0, 3)])].slice(0, 4);

    return keywords.map((name, index) => ({
      name: name.toLowerCase().replace(/[^a-z0-9_-]/g, ''),
      description: `Custom command generated from your bot description.`,
      response: `This is the ${name} command from Rose AI. You can customize this response in your bot description.`
    }));
  }

  if (!commands.some((cmd) => cmd.name === 'help')) {
    commands.unshift({
      name: 'help',
      description: 'Shows all available commands for this bot.',
      response: `Available commands: ${commands.map((cmd) => `\`${cmd.name}\``).join(', ')}.`
    });
  }

  return commands;
}

function createBotClient() {
  const client = new Client({
    intents: [
      GatewayIntentBits.Guilds,
      GatewayIntentBits.GuildMessages,
      GatewayIntentBits.MessageContent
    ]
  });

  const commandMap = parseBotDescription(BOT_DESCRIPTION);

  client.once('ready', async () => {
    console.log(`✅ ${BOT_NAME} is online as ${client.user.tag}`);

    const slashCommands = commandMap.map((cmd) => ({
      name: cmd.name,
      description: cmd.description || `Runs the ${cmd.name} command.`
    }));

    try {
      await client.application.commands.set(slashCommands);
      console.log(`Registered ${slashCommands.length} slash commands.`);
    } catch (error) {
      console.error('Unable to register slash commands:', error.message);
    }
  });

  client.on('interactionCreate', async (interaction) => {
    if (!interaction.isChatInputCommand()) return;

    const command = commandMap.find((cmd) => cmd.name === interaction.commandName.toLowerCase());
    if (!command) return;

    try {
      if (command.name === 'help') {
        const list = commandMap.map((entry) => `\`${entry.name}\``).join(', ');
        await interaction.reply({
          embeds: [new EmbedBuilder()
            .setColor('#ff5ea8')
            .setTitle('Rose AI Commands')
            .setDescription(list)
            .setFooter({ text: 'Powered by Rose AI' })]
        });
        return;
      }

      await interaction.reply({
        embeds: [new EmbedBuilder()
          .setColor('#5ab6ff')
          .setTitle(`${BOT_NAME} • ${command.name}`)
          .setDescription(command.response)
          .setFooter({ text: 'Generated by Rose AI' })]
      });
    } catch (error) {
      console.error('Interaction failed:', error);
    }
  });

  client.on('messageCreate', async (message) => {
    if (message.author.bot || !message.content.startsWith('!')) return;

    const [rawCommand, ...args] = message.content.slice(1).trim().split(/\s+/);
    const commandName = rawCommand.toLowerCase();
    const command = commandMap.find((cmd) => cmd.name === commandName);

    if (!command) {
      const helpText = commandMap.map((cmd) => `\`${cmd.name}\``).join(', ');
      await message.reply(`Unknown command. Try: ${helpText}`);
      return;
    }

    if (command.name === 'help') {
      await message.reply(`Available commands: ${commandMap.map((item) => `\`${item.name}\``).join(', ')}`);
      return;
    }

    await message.reply(command.response);
  });

  return client;
}

app.get('/api/config', (req, res) => {
  res.json({
    botName: BOT_NAME,
    botDescription: BOT_DESCRIPTION,
    discordTokenConfigured: Boolean(DISCORD_TOKEN),
    clientIdConfigured: Boolean(DISCORD_CLIENT_ID),
    inviteLink: DISCORD_CLIENT_ID
      ? `https://discord.com/oauth2/authorize?client_id=${DISCORD_CLIENT_ID}&scope=bot%20applications.commands&permissions=8`
      : null
  });
});

app.post('/api/build', (req, res) => {
  const botName = normalizeValue(req.body.botName) || 'Rose AI';
  const description = normalizeValue(req.body.description) || 'help: Show commands\nping: Check bot status';
  const token = normalizeValue(req.body.token);
  const clientId = normalizeValue(req.body.clientId);

  if (!token) {
    return res.status(400).json({
      error: 'A Discord bot token is required.'
    });
  }

  const envText = [
    'DISCORD_TOKEN=' + token,
    'DISCORD_CLIENT_ID=' + clientId,
    'BOT_NAME=' + botName,
    'BOT_DESCRIPTION=' + description
  ].join('\n');

  const generatedConfig = {
    botName,
    botDescription: description,
    token,
    clientId,
    renderEnv: envText,
    inviteLink: clientId
      ? `https://discord.com/oauth2/authorize?client_id=${clientId}&scope=bot%20applications.commands&permissions=8`
      : null
  };

  fs.writeFileSync(path.join(__dirname, 'generated.env'), envText, 'utf8');

  res.json({
    success: true,
    ...generatedConfig,
    instructions: 'Add the generated values to your Render service environment variables and redeploy.'
  });
});

app.get('*', (req, res) => {
  res.sendFile(path.join(__dirname, 'public', 'index.html'));
});

async function startServer() {
  app.listen(PORT, async () => {
    console.log(`🌐 Rose AI server running on http://localhost:${PORT}`);

    if (DISCORD_TOKEN) {
      try {
        const client = createBotClient();
        await client.login(DISCORD_TOKEN);
        console.log('✅ Discord client connected.');
      } catch (error) {
        console.error('Discord login failed:', error.message);
      }
    } else {
      console.log('ℹ️ No DISCORD_TOKEN set. Add one to run the bot locally or on Render.');
    }
  });
}

startServer();
